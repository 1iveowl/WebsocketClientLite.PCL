#!/usr/bin/env bash
# Verify and regenerate with the checksum-pinned Linux x64 toolchain.
set -euo pipefail
cd "$(dirname "$0")/.."
mode="${1:---check}"
[[ "$mode" == --check || "$mode" == --write ]] || { echo 'Usage: dafny-masking.sh [--check|--write]' >&2; exit 2; }
version=4.11.0
checksum=a46a9ff7cdd720f7955854c78e95df13f4cfe6b80691b05f8654fe19e8267179
tool_dir="${XDG_CACHE_HOME:-$HOME/.cache}/websocketclientlite/dafny-$version"
if [[ ! -f "$tool_dir/.verified-archive" ]]; then
  [[ "$(uname -s)-$(uname -m)" == Linux-x86_64 ]] || { echo 'Pinned generator requires Linux x64 (use the dev container).' >&2; exit 1; }
  temporary=$(mktemp -d)
  trap 'rm -rf "$temporary"' EXIT
  curl --fail --location --silent --show-error "https://github.com/dafny-lang/dafny/releases/download/v$version/dafny-$version-x64-ubuntu-22.04.zip" -o "$temporary/dafny.zip"
  echo "$checksum  $temporary/dafny.zip" | sha256sum --check
  mkdir -p "$tool_dir"
  unzip -q -o "$temporary/dafny.zip" -d "$tool_dir"
  touch "$tool_dir/.verified-archive"
fi
mkdir -p artifacts/dafny
"$tool_dir/dafny/dafny" --version
"$tool_dir/dafny/z3/bin/z3-4.12.1" --version
# Audit BOTH roots explicitly: Dafny audit does not include included files by default.
# New assumptions/externs must change the reviewed trust report, never slip in silently.
"$tool_dir/dafny/dafny" audit verification/Masking.dfy verification/Protocol.dfy \
  --allow-external-contracts --report-file artifacts/dafny/trusted-boundaries.md --report-format md
diff -u verification/trusted-boundaries.md artifacts/dafny/trusted-boundaries.md
# NativeCopy.CopySlice is the one explicit external contract: System.Buffer.BlockCopy.
# See verification/README.md for its trust boundary and independent adapter tests.
"$tool_dir/dafny/dafny" translate cs verification/Masking.dfy \
  --solver-path "$tool_dir/dafny/z3/bin/z3-4.12.1" \
  --verify-included-files --allow-external-contracts --verification-time-limit 30 --cores 2 \
  --output artifacts/dafny/Masking.cs
# The command line contains a machine-specific solver path in an assembly metadata
# string. Normalize that metadata only, and hide the generated types from public API.
python3 - "$tool_dir" <<'PY'
from pathlib import Path
import sys
p = Path('artifacts/dafny/Masking.cs')
s = p.read_text().replace(sys.argv[1], '<pinned-toolchain>')
s = s.replace('public partial class ', 'internal partial class ')
p.write_text('// <auto-generated/>\n#nullable disable\n' + s)
PY
if [[ "$mode" == --write ]]; then
  cp artifacts/dafny/Masking.cs verification/generated/Masking.g.cs
else
  diff -u verification/generated/Masking.g.cs artifacts/dafny/Masking.cs
fi
