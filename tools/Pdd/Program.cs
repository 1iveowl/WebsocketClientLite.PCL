using System.Globalization;
using System.Runtime.InteropServices;

namespace Pdd;

public static class Program
{
    public static string FindRoot()
    {
        foreach (var start in new[] { AppContext.BaseDirectory, Directory.GetCurrentDirectory() })
            for (var dir = new DirectoryInfo(start); dir is not null; dir = dir.Parent)
                if (File.Exists(Path.Combine(dir.FullName, "verification/requirements.schema.json")))
                    return dir.FullName;
        throw new InvalidDataException("Cannot locate repository root");
    }
    public static void Normalize(string file, string toolDirectory) => File.WriteAllText(file, "// <auto-generated/>\n#nullable disable\n" + Data.Text(file).Replace(toolDirectory, "<pinned-toolchain>").Replace("public partial class ", "internal partial class "));
    public static async Task<int> Main(string[] args)
    {
        using var cancellation = new CancellationTokenSource();
        Console.CancelKeyPress += (_, e) => { e.Cancel = true; cancellation.Cancel(); };
        using var term = OperatingSystem.IsWindows() ? null : PosixSignalRegistration.Create(PosixSignal.SIGTERM, c => { c.Cancel = true; cancellation.Cancel(); });
        using var interrupt = OperatingSystem.IsWindows() ? null : PosixSignalRegistration.Create(PosixSignal.SIGINT, c => { c.Cancel = true; cancellation.Cancel(); });
        try
        {
            if (args.Length == 0)
                throw new ArgumentException("Usage: pdd <validate|contract-report|mutations|capture|test-target|aggregate|controlled-defect|boundary-defects|queued-defect|queued-probe|lease-defects|lease-probe|retention-defects|stryker-triage|normalize-generated> [options]");
            var root = FindRoot();
            var options = new Dictionary<string, string>();
            var positionals = new List<string>();
            for (int i = 1; i < args.Length; i++)
            {
                if (args[i].StartsWith("--"))
                {
                    if (i + 1 == args.Length || args[i + 1].StartsWith("--"))
                        throw new ArgumentException($"Missing value for {args[i]}");
                    if (!options.TryAdd(args[i], args[++i]))
                        throw new ArgumentException("Duplicate option");
                }
                else
                    positionals.Add(args[i]);
            }
            string Get(string key, string? fallback = null) => options.GetValueOrDefault(key) ?? fallback ?? throw new ArgumentException($"{args[0]} requires {key}");
            void Allow(params string[] names)
            {
                if (options.Keys.Except(names).Any())
                    throw new ArgumentException("Unknown option: " + string.Join(", ", options.Keys.Except(names)));
                if (args[0] != "validate" && positionals.Count > 0 || positionals.Count > 1)
                    throw new ArgumentException("Unexpected positional argument");
            }
            double Number(string key, string fallback) => double.TryParse(Get(key, fallback), CultureInfo.InvariantCulture, out var number) ? number : throw new ArgumentException($"Invalid number for {key}");
            int Integer(string key, string fallback) => int.TryParse(Get(key, fallback), out var number) ? number : throw new ArgumentException($"Invalid integer for {key}");
            string Choice(string key, string[] choices) => choices.Contains(Get(key)) ? Get(key) : throw new ArgumentException($"Invalid choice for {key}");
            var evidence = new Evidence(root);
            var output = Path.GetFullPath(Get("--output", "artifacts/pdd"));
            switch (args[0])
            {
                case "validate":
                    Allow();
                    var manifest = new Requirements(root).Validate(positionals.Count == 1 ? Data.Read(positionals[0]) : null);
                    Console.WriteLine($"Validated {manifest.Requirements.Length} requirements (structure and references only; no evidence executed).");
                    return 0;
                case "contract-report":
                    Allow("--target", "--head", "--output");
                    var report = await ContractReport.Report(root, Get("--target"), Get("--head", "HEAD"), cancellation.Token);
                    var reportPath = Path.GetFullPath(Get("--output"));
                    Directory.CreateDirectory(Path.GetDirectoryName(reportPath)!);
                    File.WriteAllText(reportPath, report);
                    Console.WriteLine($"Contract-change report: {reportPath} (review aid only).");
                    return 0;
                case "mutations":
                    Allow("--output", "--baseline-budget", "--mutant-budget", "--verification-time-limit", "--scope");
                    return await new Mutations(root).Run(Path.GetFullPath(Get("--output", Path.Combine(root, "artifacts/close-mutations", DateTime.UtcNow.ToString("yyyyMMddTHHmmss.fffffffZ")))), Number("--baseline-budget", "180"), Number("--mutant-budget", "90"), Integer("--verification-time-limit", "60"), cancellation.Token, Get("--scope", "all"));
                case "capture":
                    Allow("--job", "--output", "--command-budget");
                    return await evidence.Capture(Choice("--job", ["protocol", "tests", "controlled", "stryker"]), output, Number("--command-budget", "1800"), cancellation.Token);
                case "stryker-triage":
                    Allow("--report", "--output");
                    var triage = Evidence.TriageStryker(Data.Read(Get("--report")), Data.Read(Path.Combine(root, "verification/stryker-close-dispositions.json")), Data.Hash(File.ReadAllBytes(Path.Combine(root, Evidence.CloseSource))));
                    Data.Save(Path.Combine(output, "stryker-triage.json"), triage);
                    return 0;
                case "boundary-defects":
                    Allow("--output");
                    return await evidence.BoundaryDefects(output, cancellation.Token);
                case "reconnect-defect":
                    Allow("--output");
                    return await evidence.ReconnectDefects(output, cancellation.Token);
                case "retention-defects":
                    Allow("--output");
                    return await evidence.RetentionDefects(output, cancellation.Token);
                case "lease-defects":
                    Allow("--output");
                    return await evidence.LeaseDefects(output, cancellation.Token);
                case "lease-probe":
                    Allow("--output");
                    return await evidence.LeaseProbe(output, cancellation.Token);
                case "queued-probe":
                    Allow("--output");
                    return await evidence.QueuedProbe(output, cancellation.Token);
                case "queued-defect":
                    Allow("--output");
                    return await evidence.QueuedDefect(output, cancellation.Token);
                case "controlled-defect":
                    Allow("--output");
                    return await evidence.ControlledDefect(output, cancellation.Token);
                case "test-target":
                    Allow("--tfm", "--output", "--command-budget");
                    return await evidence.TestTarget(Choice("--tfm", Evidence.Tfms), output, Number("--command-budget", "1800"), cancellation.Token);
                case "aggregate":
                    Allow("--output");
                    Directory.CreateDirectory(output);
                    var receipt = evidence.Aggregate(output, await evidence.Identity());
                    Data.Save(Path.Combine(output, "receipt.json"), receipt);
                    var summary = Evidence.Summary(receipt);
                    File.WriteAllText(Path.Combine(output, "summary.md"), summary);
                    if (Environment.GetEnvironmentVariable("GITHUB_STEP_SUMMARY") is { Length: > 0 } summaryPath)
                        File.AppendAllText(summaryPath, summary);
                    Console.Write(summary);
                    return receipt["gate"]!["status"]!.ToString() == "passed" ? 0 : 1;
                case "normalize-generated":
                    Allow("--file", "--tool-directory");
                    Normalize(Get("--file"), Get("--tool-directory"));
                    return 0;
                default:
                    throw new ArgumentException("Unknown command: " + args[0]);
            }
        }
        catch (ArgumentException error) { Console.Error.WriteLine(error.Message); return 2; }
        catch (Exception error) when (error is not OutOfMemoryException) { Console.Error.WriteLine($"pdd: {error.Message}"); return 1; }
    }
}
